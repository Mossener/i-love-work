// Diagram labels are accessible through SVG itself; omit them from reading text
// so a diagram's labels do not duplicate the surrounding manuscript's words.
function readingText(html: string): string {
  return html
    .replace(/<svg\b[^>]*>[\s\S]*?<\/svg>/gi, " ")
    .replace(/<[^>]*>/g, " ")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/\s+/g, " ")
    .trim();
}

function makeChapter(
  chapter: (typeof manuscript)[number],
  index: number,
): BookChapter {
  const text = readingText(chapter.html);
  const chineseCharacters =
    text.match(/[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff]/g)?.length ?? 0;
  const latinWords = text.match(/[A-Za-z]+(?:['’\-][A-Za-z]+)*/g)?.length ?? 0;
  return {
    id: `demo-chapter-${index + 1}`,
    title: chapter.title,
    href: `demo/chapter-${index + 1}.xhtml`,
    html: chapter.html.trim(),
    text,
    wordCount: chineseCharacters + latinWords,
    imageCount: chapter.html.match(/<(?:img|svg)\b/gi)?.length ?? 0,
  };
}

const chapters = manuscript.map(makeChapter);

